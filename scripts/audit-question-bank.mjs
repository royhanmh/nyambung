import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dataPath = path.join(root, "src", "data", "nyambung-1000-questions-id-ID.json");
const data = JSON.parse(fs.readFileSync(dataPath, "utf8"));
const questions = data.questions ?? [];
const errors = [];

const countBy = (items, key) =>
  items.reduce((counts, item) => {
    const value = item[key];
    counts[value] = (counts[value] ?? 0) + 1;
    return counts;
  }, {});

const normalizedWords = (text) =>
  new Set(
    text
      .toLowerCase()
      .replace(/[^\p{L}\p{N}\s]/gu, " ")
      .split(/\s+/)
      .filter(Boolean),
  );

const jaccard = (left, right) => {
  const intersection = [...left].filter((word) => right.has(word)).length;
  const union = new Set([...left, ...right]).size;
  return union === 0 ? 0 : intersection / union;
};

if (questions.length !== 1000) errors.push(`expected 1000 questions, got ${questions.length}`);

const ids = questions.map((question) => question.id);
const texts = questions.map((question) => question.text.trim().toLowerCase());

if (new Set(ids).size !== ids.length) errors.push("duplicate question ids");
if (new Set(texts).size !== texts.length) errors.push("duplicate question texts");

const categoryCounts = countBy(questions, "category");
for (const [category, count] of Object.entries(categoryCounts)) {
  if (count !== 100) errors.push(`${category} has ${count} questions; expected 100`);
}

const bannedPatterns = [
  /inner child/i,
  /healing journey/i,
  /love language/i,
  /sebagai ai/i,
  /generated by ai/i,
];

questions.forEach((question, index) => {
  if (!question.text?.trim()) errors.push(`question ${index + 1} is empty`);
  if (!question.text.trim().endsWith("?")) errors.push(`${question.id} must end with ?`);
  if (question.text.trim().length > 150) errors.push(`${question.id} is over 150 characters`);
  if (bannedPatterns.some((pattern) => pattern.test(question.text))) {
    errors.push(`${question.id} contains banned therapy/AI language`);
  }
});

const wordSets = questions.map((question) => normalizedWords(question.text));
for (let left = 0; left < questions.length; left += 1) {
  for (let right = left + 1; right < questions.length; right += 1) {
    if (jaccard(wordSets[left], wordSets[right]) >= 0.82) {
      errors.push(`near-duplicate: ${questions[left].id} / ${questions[right].id}`);
    }
  }
}

const relationships = ["friends", "couple", "pdk_t", "new_people", "group", "family"];
for (const relationship of relationships) {
  const count = questions.filter((question) => question.relationships?.includes(relationship)).length;
  if (count < 80) errors.push(`${relationship} has only ${count} questions`);
}

const depthCounts = countBy(questions, "depth");
if (Object.keys(depthCounts).length < 4) errors.push("depth coverage is too narrow");

if (errors.length > 0) {
  console.error(errors.join("\n"));
  process.exit(1);
}

console.log(`Question bank valid: ${questions.length} questions`);
